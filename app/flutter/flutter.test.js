const test = require('node:test');
const assert = require('node:assert/strict');
const { parseUmlModel } = require('../generation/parseUml');
const { buildBackendModel } = require('../generation/buildBackendModel');
const { buildOpenApiYaml } = require('../generation/buildOpenApi');
const { buildFrontendModel } = require('./buildFrontendModel');
const { validateFrontendModel } = require('./validateFrontendModel');
const { writeFlutterFiles } = require('./writeFlutterProject');

function sample() {
  return parseUmlModel(
    {
      classes: [
        {
          id: 'u1',
          name: 'Usuario',
          attributes: ['- id: Long', '+ nombre: String', '+ email: String'],
          methods: [],
        },
      ],
      relations: [],
    },
    'd1'
  );
}

test('builds list, detail and form screens from the backend model', () => {
  const backend = buildBackendModel(sample(), { database: 'h2' });
  const frontend = buildFrontendModel(backend, { baseUrl: 'http://127.0.0.1:8081' });
  assert.equal(validateFrontendModel(frontend).ok, true);
  assert.ok(frontend.screens.some((item) => item.type === 'list' && item.entity === 'Usuario'));
  assert.ok(frontend.screens.some((item) => item.type === 'form'));
  assert.equal(frontend.backend.baseUrl, 'http://127.0.0.1:8081');
});

test('writes Dio client, repository and Flutter screens without inventing endpoints', () => {
  const backend = buildBackendModel(sample(), { database: 'h2' });
  const frontend = buildFrontendModel(backend, { baseUrl: 'http://127.0.0.1:8081' });
  const files = writeFlutterFiles(frontend, buildOpenApiYaml(backend));
  assert.ok(files['pubspec.yaml'].includes('dio:'));
  assert.ok(files['lib/generated/api/usuario_api.dart'].includes('/api/usuarios'));
  assert.ok(files['lib/generated/api/usuario_api.dart'].includes('GENERATED BY TRAZO'));
  assert.ok(files['lib/features/usuario/presentation/usuario_list_screen.dart']);
  assert.ok(files['lib/core/config/api_config.dart'].includes('127.0.0.1:8081'));
  assert.ok(files['trazo.project.json'].includes('flutter'));
  assert.match(files['lib/features/usuario/presentation/usuario_form_screen.dart'], /int\.tryParse|_nombre\.text\.trim\(\)\.isEmpty/);
  assert.match(files['lib/generated/models/usuario.dart'], /id != 0/);
  assert.match(files['lib/features/usuario/data/usuario_repository.dart'], /\.\.\/\.\.\/\.\.\/generated\/api\/usuario_api.dart/);
});
