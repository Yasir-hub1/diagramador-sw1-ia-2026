const { snakeCase, dartType, dartFormValue } = require('./dartTypes');

const GENERATED = '// GENERATED BY TRAZO. DO NOT EDIT MANUALLY.\n';

function dartParse(type, key) {
  if (type === 'int') return "json['" + key + "'] is num ? (json['" + key + "'] as num).toInt() : 0";
  if (type === 'double') return "json['" + key + "'] is num ? (json['" + key + "'] as num).toDouble() : 0";
  if (type === 'bool') return "json['" + key + "'] == true";
  return "json['" + key + "']?.toString() ?? ''";
}

function modelFile(entity) {
  const fields = entity.attributes
    .map((item) => '  final ' + dartType(item.type) + '? ' + item.name + ';')
    .join('\n');
  const ctor = entity.attributes.map((item) => '    this.' + item.name + ',').join('\n');
  const from = entity.attributes
    .map((item) => '      ' + item.name + ': ' + dartParse(dartType(item.type), item.name) + ',')
    .join('\n');
  const to = entity.attributes.map(dartToJsonAssign).join('\n');
  return (
    GENERATED +
    'class ' +
    entity.name +
    ' {\n' +
    fields +
    '\n\n  const ' +
    entity.name +
    '({\n' +
    ctor +
    '\n  });\n\n  factory ' +
    entity.name +
    '.fromJson(Map<String, dynamic> json) {\n    return ' +
    entity.name +
    '(\n' +
    from +
    '\n    );\n  }\n\n  Map<String, dynamic> toJson() {\n    final json = <String, dynamic>{};\n' +
    to +
    '\n    return json;\n  }\n}\n'
  );
}

function dartToJsonAssign(item) {
  const name = item.name;
  if (item.primaryKey) {
    return "    if (" + name + " != null && " + name + " != 0) json['" + name + "'] = " + name + ";";
  }
  if (dartType(item.type) === 'String') {
    return "    if (" + name + " != null && " + name + "!.isNotEmpty) json['" + name + "'] = " + name + ";";
  }
  return "    if (" + name + " != null) json['" + name + "'] = " + name + ";";
}

