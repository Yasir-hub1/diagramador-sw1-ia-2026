function writeFlutterFiles(model, openApiYaml) {
  const files = appFiles(model);
  files['openapi.yaml'] = openApiYaml || '';
  model.entities.forEach((entity) => {
    const slug = snakeCase(entity.name);
    files['lib/generated/models/' + slug + '.dart'] = modelFile(entity);
    files['lib/generated/api/' + slug + '_api.dart'] = apiFile(entity);
    files['lib/features/' + slug + '/data/' + slug + '_repository.dart'] = repositoryFile(entity);
    files['lib/features/' + slug + '/domain/' + slug + '_provider.dart'] = providerFile(entity);
    files['lib/features/' + slug + '/presentation/' + slug + '_list_screen.dart'] = listScreen(entity);
    files['lib/features/' + slug + '/presentation/' + slug + '_detail_screen.dart'] = detailScreen(entity);
    files['lib/features/' + slug + '/presentation/' + slug + '_form_screen.dart'] = formScreen(entity);
  });
  return files;
}

