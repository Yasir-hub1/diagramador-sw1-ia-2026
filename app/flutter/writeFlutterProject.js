function formPayloadLines(fields) {
  const lines = ['    final body = <String, dynamic>{};'];
  fields.forEach((item) => {
    const expr = dartFormValue(item.type, '_' + item.name + '.text');
    lines.push('    final ' + item.name + ' = ' + expr + ';');
    if (item.type === 'Boolean') {
      lines.push("    body['" + item.name + "'] = " + item.name + ';');
    } else {
      lines.push('    if (' + item.name + " != null) body['" + item.name + "'] = " + item.name + ';');
    }
  });
  return lines.join('\n') + '\n';
}

function formScreen(entity) {
  const fields = entity.attributes.filter((item) => !item.primaryKey);
  const controllers = fields
    .map((item) => '  final _' + item.name + " = TextEditingController();")
    .join('\n');
  const inputs = fields
    .map(
      (item) =>
        "            TextField(controller: _" +
        item.name +
        ", decoration: const InputDecoration(labelText: '" +
        item.name +
        "')),"
    )
    .join('\n');
  const body = formPayloadLines(fields);
  const dispose = fields.map((item) => '    _' + item.name + '.dispose();').join('\n');
  const slug = snakeCase(entity.name);
  return (
    GENERATED +
    "import 'package:flutter/material.dart';\n" +
    "import 'package:flutter_riverpod/flutter_riverpod.dart';\n" +
    "import 'package:go_router/go_router.dart';\n" +
    "import '../domain/" +
    slug +
    "_provider.dart';\n\n" +
    'class ' +
    entity.name +
    'FormScreen extends ConsumerStatefulWidget {\n' +
    '  const ' +
    entity.name +
    'FormScreen({super.key});\n\n' +
    '  @override\n' +
    '  ConsumerState<' +
    entity.name +
    'FormScreen> createState() => _' +
    entity.name +
    'FormScreenState();\n}\n\n' +
    'class _' +
    entity.name +
    'FormScreenState extends ConsumerState<' +
    entity.name +
    'FormScreen> {\n' +
    controllers +
    '\n\n  @override\n  void dispose() {\n' +
    dispose +
    '\n    super.dispose();\n  }\n\n' +
    '  Future<void> _save() async {\n' +
    body +
    '    await ref.read(' +
    slug +
    'RepositoryProvider).create(body);\n' +
    '    if (mounted) context.pop();\n' +
    '  }\n\n' +
    '  @override\n' +
    '  Widget build(BuildContext context) {\n' +
    "    return Scaffold(appBar: AppBar(title: const Text('Nuevo " +
    entity.name +
    "')), body: ListView(padding: const EdgeInsets.all(16), children: [\n" +
    inputs +
    '\n            const SizedBox(height: 16),\n' +
    "            FilledButton(onPressed: _save, child: const Text('Guardar')),\n" +
    '    ]));\n' +
    '  }\n}\n'
  );
}

